"""Build and render Bingo Royale's asset studio in Unreal Editor 5.8.

Enable PythonScriptPlugin, EditorScriptingUtilities, SequencerScripting and
MovieRenderPipeline in the dedicated look-development project. Run in the editor:

    import runpy
    studio = runpy.run_path('/absolute/path/to/render_unreal.py')
    studio['main'](preview=True)  # blue ball and gold star, 512 px
    studio['main'](preview=False, build=False)  # all 14 assets, 1024 px

The render is asynchronous. Keep the editor running until renders/status.json
reports "complete". All Unreal content is confined to /Game/BingoLookdev.
Source FBX files are generated by export_blender_icons.py. Unreal, not Blender,
calculates every delivered pixel's lighting, reflections and filmic tone curve.
"""

import datetime
import json
import traceback
from pathlib import Path

import unreal


SOURCE_DIR = Path(__file__).resolve().parent
SOURCE_MESHES = SOURCE_DIR / 'SourceMeshes'
DEFAULT_OUTPUT = SOURCE_DIR / 'renders'
CONTENT = '/Game/BingoLookdev'
BALLS = {'b': '#216dff', 'i': '#ef4444', 'n': '#a78bfa', 'g': '#22c55e', 'o': '#f59e0b'}
ICONS = {
    'wild_square': 'SM_WildSquare', 'shield': 'SM_Shield',
    'turbo_stamp': 'SM_TurboStamp', 'ink_blot': 'SM_InkBlot',
    'number_peek': 'SM_NumberPeek', 'scramble': 'SM_Scramble',
    'callers_choice': 'SM_CallersChoice', 'double_daub': 'SM_DoubleDaub',
    'crown': 'SM_Crown',
}

# UObject references and delegates must survive the asynchronous MRQ execution.
STATE = {'phase': 'idle'}
EXECUTOR = None
QUEUE = None
OUTPUT = DEFAULT_OUTPUT


def report(phase, **details):
    STATE.update(phase=phase, updated_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(), **details)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT / 'status.tmp.json'
    temporary.write_text(json.dumps(STATE, indent=2), encoding='utf-8')
    temporary.replace(OUTPUT / 'status.json')
    unreal.log('[BingoUnreal] ' + phase + ' ' + json.dumps(details, default=str))


def set_properties(obj, **properties):
    for name, value in properties.items():
        obj.set_editor_property(name, value)


def linear_hex(color):
    values = [int(color[i:i + 2], 16) / 255.0 for i in (1, 3, 5)]
    return [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in values]


def asset_path(folder, name):
    return '{}/{}/{}'.format(CONTENT, folder, name)


def make_material(name, color, metallic=0.0, roughness=.30, coat=.28, coat_roughness=.16):
    """Linear PBR, controlled clear coat, and restrained roughness variation.

    UE5.8 exposes MP_MATERIAL_ATTRIBUTES. Connecting named ClearCoat inputs on
    MakeMaterialAttributes avoids the hidden CustomData0/1 enum entries while
    preserving explicit coat coverage and roughness in the compiled shader.
    """
    path = asset_path('Materials', name)
    if unreal.EditorAssetLibrary.does_asset_exist(path):
        material = unreal.load_asset(path)
    else:
        material = unreal.AssetToolsHelpers.get_asset_tools().create_asset(
            name, CONTENT + '/Materials', unreal.Material, unreal.MaterialFactoryNew())
    material.set_editor_property('shading_model', unreal.MaterialShadingModel.MSM_CLEAR_COAT
                                 if coat > 0 else unreal.MaterialShadingModel.MSM_DEFAULT_LIT)
    material.set_editor_property('use_material_attributes', True)
    edit = unreal.MaterialEditingLibrary
    edit.delete_all_material_expressions(material)
    attributes = edit.create_material_expression(material, unreal.MaterialExpressionMakeMaterialAttributes, 100, 0)

    def connect(node, pin):
        if not edit.connect_material_expressions(node, '', attributes, pin):
            raise RuntimeError('Could not connect material input ' + pin + ' on ' + name)

    def scalar(value, pin, y):
        node = edit.create_material_expression(material, unreal.MaterialExpressionConstant, -200, y)
        node.set_editor_property('r', float(value))
        connect(node, pin)

    base = edit.create_material_expression(material, unreal.MaterialExpressionConstant3Vector, -240, -160)
    base.set_editor_property('constant', unreal.LinearColor(*list(color[:3]), 1.0))
    connect(base, 'BaseColor')
    scalar(metallic, 'Metallic', 0)
    scalar(coat, 'ClearCoat', 180)
    scalar(coat_roughness, 'ClearCoatRoughness', 260)
    scalar(.5, 'Specular', 340)
    # The built-in noise's default position is world space (centimetres).
    # A restrained 0.06-wide range breaks uniform plastic reflections without dirt.
    noise = edit.create_material_expression(material, unreal.MaterialExpressionNoise, -240, 80)
    set_properties(noise, scale=1.4, quality=1, levels=2,
                   output_min=max(.02, roughness - .03), output_max=min(.98, roughness + .03))
    connect(noise, 'Roughness')
    if not edit.connect_material_property(attributes, '', unreal.MaterialProperty.MP_MATERIAL_ATTRIBUTES):
        raise RuntimeError('Could not connect material attributes on ' + name)
    edit.recompile_material(material)
    unreal.EditorAssetLibrary.save_loaded_asset(material)
    return material


def import_icons(manifest, materials):
    meshes = {}
    entries = list(manifest['assets'])
    ball_entry = manifest.get('ball_mesh')
    if ball_entry:
        entries.append(ball_entry)
    for entry in entries:
        name = entry['name']
        destination = asset_path('Meshes', name)
        mesh = unreal.load_asset(destination) if unreal.EditorAssetLibrary.does_asset_exist(destination) else None
        if mesh is None:
            filename = SOURCE_MESHES / entry['fbx']
            if not filename.is_file():
                raise FileNotFoundError(str(filename))
            options = unreal.FbxImportUI()
            set_properties(options, import_mesh=True, import_materials=False, import_textures=False,
                           import_as_skeletal=False, automated_import_should_detect_type=False,
                           mesh_type_to_import=unreal.FBXImportType.FBXIT_STATIC_MESH)
            data = options.get_editor_property('static_mesh_import_data')
            set_properties(data, combine_meshes=True, convert_scene=True, convert_scene_unit=True,
                           force_front_x_axis=True, import_uniform_scale=1.0,
                           normal_import_method=unreal.FBXNormalImportMethod.FBXNIM_IMPORT_NORMALS)
            task = unreal.AssetImportTask()
            set_properties(task, filename=str(filename), destination_path=CONTENT + '/Meshes',
                           destination_name=name, automated=True, replace_existing=True,
                           save=True, options=options, factory=unreal.FbxFactory())
            unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
            mesh = unreal.load_asset(destination)
            if mesh is None:
                candidates = [unreal.load_asset(p) for p in task.get_editor_property('imported_object_paths')]
                mesh = next((p for p in candidates if isinstance(p, unreal.StaticMesh)), None)
            if mesh is None:
                raise RuntimeError('FBX import produced no StaticMesh for ' + name)
        # Use the actual imported slot names; the exporter preserves these names.
        for index, slot in enumerate(mesh.get_editor_property('static_materials')):
            # The high-resolution ball's one neutral source slot is overridden
            # by a different resin material in each of the five studio maps.
            if ball_entry and name == ball_entry['name']:
                continue
            imported_name = str(slot.get_editor_property('imported_material_slot_name'))
            display_name = str(slot.get_editor_property('material_slot_name'))
            canonical = next((m for m in materials if m == imported_name or m == display_name), None)
            if canonical is None:
                canonical = next((m for m in entry['material_slots'] if m in imported_name or m in display_name), None)
            if canonical is None:
                # Manifest order is the final fallback for FBX importers sanitizing names.
                canonical = entry['material_slots'][index] if index < len(entry['material_slots']) else None
            if canonical not in materials:
                raise RuntimeError('Unmapped material slot {} on {}'.format(display_name, name))
            mesh.set_material(index, materials[canonical])
        unreal.EditorAssetLibrary.save_loaded_asset(mesh)
        meshes[name] = mesh
        report('importing', current_asset=name)
    return meshes


def spawn(actor_class, label, position, rotation=None):
    subsystem = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    actor = subsystem.spawn_actor_from_class(actor_class, unreal.Vector(*position), rotation or unreal.Rotator())
    if actor is None:
        raise RuntimeError('Could not spawn ' + label)
    actor.set_actor_label(label)
    actor.set_editor_property('tags', [unreal.Name('BingoLookdev')])
    return actor


def rect_light(label, position, lumens, size, temperature, target=(0, 0, 0)):
    rotation = unreal.MathLibrary.find_look_at_rotation(unreal.Vector(*position), unreal.Vector(*target))
    actor = spawn(unreal.RectLight, label, position, rotation)
    light = actor.get_component_by_class(unreal.RectLightComponent)
    light.set_mobility(unreal.ComponentMobility.MOVABLE)
    light.set_intensity_units(unreal.LightUnits.LUMENS)
    light.set_intensity(float(lumens))
    light.set_source_width(float(size[0]))
    light.set_source_height(float(size[1]))
    light.set_temperature(float(temperature))
    light.set_use_temperature(True)
    light.set_attenuation_radius(1200.0)
    return actor


def studio_post_process(exposure):
    post = unreal.PostProcessSettings()
    overrides = {
        'auto_exposure_method': unreal.AutoExposureMethod.AEM_MANUAL,
        'auto_exposure_apply_physical_camera_exposure': False,
        'auto_exposure_bias': float(exposure),
        'dynamic_global_illumination_method': unreal.DynamicGlobalIlluminationMethod.LUMEN,
        'reflection_method': unreal.ReflectionMethod.LUMEN,
        'lumen_scene_lighting_quality': 4.0,
        'lumen_final_gather_quality': 4.0,
        'lumen_reflection_quality': 4.0,
        'motion_blur_amount': 0.0,
        'bloom_intensity': 0.0,
        'vignette_intensity': 0.0,
        'film_grain_intensity': 0.0,
        'scene_fringe_intensity': 0.0,
    }
    for name, value in overrides.items():
        post.set_editor_property('override_' + name, True)
        post.set_editor_property(name, value)
    return post


def build_scene(name, mesh, material=None, exposure=-5.0):
    """Single subject per map avoids per-job hidden actor/sequence state leaks."""
    levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    map_path = asset_path('Maps', 'Studio_' + name)
    if unreal.EditorAssetLibrary.does_asset_exist(map_path):
        if not levels.load_level(map_path):
            raise RuntimeError('Could not load isolated map ' + map_path)
        actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
        for actor in actors.get_all_level_actors():
            if unreal.Name('BingoLookdev') in actor.get_editor_property('tags'):
                actors.destroy_actor(actor)
    elif not levels.new_level(map_path):
        raise RuntimeError('Could not create isolated map ' + map_path)
    subject = spawn(unreal.StaticMeshActor, name, (0, 0, 0))
    component = subject.get_component_by_class(unreal.StaticMeshComponent)
    component.set_static_mesh(mesh)
    if material:
        component.set_material(0, material)
    # All subjects occupy a 100 cm bounding box; framing is stable across icons.
    bounds = mesh.get_bounds()
    largest = max(bounds.box_extent.x, bounds.box_extent.y, bounds.box_extent.z) * 2.0
    if largest <= .0001:
        raise RuntimeError('Empty mesh bounds for ' + name)
    factor = 100.0 / largest
    subject.set_actor_scale3d(unreal.Vector(factor, factor, factor))
    subject.set_actor_location(unreal.Vector(-bounds.origin.x * factor, -bounds.origin.y * factor, -bounds.origin.z * factor), False, False)

    # +X is the front. A key on camera-left, high above, defines the silhouette;
    # weaker cool fill and rear light retain color instead of flattening contrast.
    is_ball = name in BALLS
    rect_light('Key - warm upper-left 5000K', (210, 170, 190), 2100, (120, 180), 5000)
    rect_light('Fill - cool lower bounce 7000K', (180, -130, -115), 400, (300, 300), 7000)
    rect_light('Rim - cool silhouette 6500K', (-145, -95, 125), 550, (140, 160), 6500)
    if not is_ball:
        rect_light('Front - broad gold reflection', (300, 100, 130), 750, (300, 250), 5500)

    camera_position = (400, 0, 0) if is_ball else (400, 15, 10)
    rotation = unreal.MathLibrary.find_look_at_rotation(unreal.Vector(*camera_position), unreal.Vector(0, 0, 0))
    camera = spawn(unreal.CameraActor, 'UI asset orthographic camera', camera_position, rotation)
    camera_component = camera.get_component_by_class(unreal.CameraComponent)
    set_properties(camera_component, projection_mode=unreal.CameraProjectionMode.ORTHOGRAPHIC,
                   ortho_width=106.0 if is_ball else 116.0, aspect_ratio=1.0,
                   constrain_aspect_ratio=False, post_process_blend_weight=1.0,
                   post_process_settings=studio_post_process(exposure))
    if not levels.save_current_level():
        raise RuntimeError('Could not save map ' + map_path)

    sequence_name = 'Render_' + name
    sequence_path = asset_path('Sequences', sequence_name)
    if unreal.EditorAssetLibrary.does_asset_exist(sequence_path):
        unreal.EditorAssetLibrary.delete_asset(sequence_path)
    sequence = unreal.AssetToolsHelpers.get_asset_tools().create_asset(
        sequence_name, CONTENT + '/Sequences', unreal.LevelSequence, unreal.LevelSequenceFactoryNew())
    sequence.set_display_rate(unreal.FrameRate(24, 1))
    sequence.set_playback_start(0)
    sequence.set_playback_end(1)
    binding = sequence.add_possessable(camera)
    track = sequence.add_track(unreal.MovieSceneCameraCutTrack)
    section = track.add_section()
    section.set_start_frame(-64)
    section.set_end_frame(1)
    binding_id = unreal.MovieSceneObjectBindingID()
    binding_id.set_editor_property('guid', binding.get_id())
    section.set_editor_property('camera_binding_id', binding_id)
    unreal.EditorAssetLibrary.save_loaded_asset(sequence)
    report('building', current_asset=name, map=map_path, sequence=sequence_path)
    return {'name': name, 'map': map_path, 'sequence': sequence_path}


def build_all(exposure=-5.0):
    manifest_path = SOURCE_MESHES / 'manifest.json'
    if not manifest_path.is_file():
        raise FileNotFoundError('Run export_blender_icons.py first: ' + str(manifest_path))
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    materials = {}
    for name, params in manifest['materials'].items():
        materials[name] = make_material(name, params['base_color'], params['metallic'],
                                        params['roughness'], params['coat'], params['coat_roughness'])
    meshes = import_icons(manifest, materials)
    ball_entry = manifest.get('ball_mesh')
    sphere = meshes.get(ball_entry['name']) if ball_entry else unreal.load_asset('/Engine/BasicShapes/Sphere.Sphere')
    if sphere is None:
        raise RuntimeError('Engine built-in sphere is unavailable')
    entries = []
    for name, color in BALLS.items():
        resin = make_material('M_Ball_' + name.upper(), linear_hex(color))
        entries.append(build_scene(name, sphere, resin, exposure))
    for name, mesh_name in ICONS.items():
        entries.append(build_scene(name, meshes[mesh_name], exposure=exposure))
    (OUTPUT / 'jobs.json').write_text(json.dumps(entries, indent=2), encoding='utf-8')
    return entries


def finished(executor, success):
    files = sorted(str(p) for p in OUTPUT.rglob('*.png'))
    report('complete' if success else 'failed', success=bool(success), rendered_files=files)


def errored(executor, pipeline, fatal, message):
    errors = list(STATE.get('errors', []))
    errors.append({'fatal': bool(fatal), 'message': str(message)})
    report('render_error' if fatal else 'render_warning', errors=errors)


def job_finished(params):
    complete = list(STATE.get('completed_jobs', []))
    complete.append(str(params.job.job_name))
    report('rendering', completed_jobs=complete)


def render_jobs(entries, resolution=1024, samples=16):
    global EXECUTOR, QUEUE
    subsystem = unreal.get_editor_subsystem(unreal.MoviePipelineQueueSubsystem)
    if subsystem.is_rendering():
        raise RuntimeError('An Unreal Movie Render Queue job is already running')
    QUEUE = subsystem.get_queue()
    QUEUE.delete_all_jobs()
    for entry in entries:
        job = QUEUE.allocate_new_job(unreal.MoviePipelineExecutorJob)
        job.job_name = entry['name']
        job.map = unreal.SoftObjectPath(entry['map'])
        job.sequence = unreal.SoftObjectPath(entry['sequence'])
        job.author = 'Bingo Royale Unreal asset studio'
        config = job.get_configuration()
        output = config.find_or_add_setting_by_class(unreal.MoviePipelineOutputSetting)
        set_properties(output, output_directory=unreal.DirectoryPath(str(OUTPUT)),
                       file_name_format=entry['name'] + '.{frame_number}',
                       output_resolution=unreal.IntPoint(resolution, resolution),
                       use_custom_playback_range=True, custom_start_frame=0, custom_end_frame=1,
                       zero_pad_frame_numbers=4, override_existing_output=True)
        deferred = config.find_or_add_setting_by_class(unreal.MoviePipelineDeferredPassBase)
        deferred.set_editor_property('accumulator_includes_alpha', True)
        config.find_or_add_setting_by_class(unreal.MoviePipelineImageSequenceOutput_PNG)
        aa = config.find_or_add_setting_by_class(unreal.MoviePipelineAntiAliasingSetting)
        set_properties(aa, spatial_sample_count=samples, temporal_sample_count=1,
                       override_anti_aliasing=True, anti_aliasing_method=unreal.AntiAliasingMethod.AAM_NONE,
                       use_camera_cut_for_warm_up=False, engine_warm_up_count=64,
                       render_warm_up_count=64, render_warm_up_frames=True)
        color = config.find_or_add_setting_by_class(unreal.MoviePipelineColorSetting)
        color.set_editor_property('disable_tone_curve', False)
        config.find_or_add_setting_by_class(unreal.MoviePipelineGameOverrideSetting)
        variables = config.find_or_add_setting_by_class(unreal.MoviePipelineConsoleVariableSetting)
        for variable, value in {
            'r.PostProcessing.PropagateAlpha': 1.0,
            'r.ScreenPercentage': 100.0,
            'r.MotionBlurQuality': 0.0,
            'r.Lumen.HardwareRayTracing': 0.0,
            'sg.GlobalIlluminationQuality': 4.0,
            'sg.ReflectionQuality': 4.0,
        }.items():
            if not variables.add_or_update_console_variable(variable, value):
                raise RuntimeError('Could not configure render CVar ' + variable)
    EXECUTOR = unreal.MoviePipelinePIEExecutor(subsystem)
    EXECUTOR.on_executor_finished_delegate.add_callable_unique(finished)
    EXECUTOR.on_executor_errored_delegate.add_callable_unique(errored)
    EXECUTOR.on_individual_job_work_finished_delegate.add_callable_unique(job_finished)
    report('rendering', queued_jobs=[e['name'] for e in entries], completed_jobs=[],
           resolution=resolution, spatial_samples=samples, errors=[])
    subsystem.render_queue_with_executor_instance(EXECUTOR)
    return EXECUTOR


def main(preview=True, build=True, render=True, output_directory=None, exposure=-5.0,
         selected_assets=None, resolution=None, samples=None):
    """Build isolated assets, then queue two previews or every production asset.

    exposure is fixed manual compensation; negative values darken the image.
    selected_assets=['b'] is useful when iterating lights. build=False reuses saved
    scenes and sequences, so changes to exposure/lights require build=True.
    """
    global OUTPUT
    OUTPUT = Path(output_directory).resolve() if output_directory else DEFAULT_OUTPUT
    OUTPUT.mkdir(parents=True, exist_ok=True)
    try:
        subsystem = unreal.get_editor_subsystem(unreal.MoviePipelineQueueSubsystem)
        if subsystem.is_rendering():
            raise RuntimeError('Wait for the current render to finish before rebuilding')
        report('starting', unreal_version=unreal.SystemLibrary.get_engine_version(),
               output_directory=str(OUTPUT), exposure=exposure)
        if build:
            entries = build_all(exposure)
        else:
            entries = [{'name': name, 'map': asset_path('Maps', 'Studio_' + name),
                        'sequence': asset_path('Sequences', 'Render_' + name)} for name in [*BALLS, *ICONS]]
        names = selected_assets or (['b', 'wild_square'] if preview else [*BALLS, *ICONS])
        unknown = set(names) - set(BALLS) - set(ICONS)
        if unknown:
            raise ValueError('Unknown assets: ' + ', '.join(sorted(unknown)))
        entries = [e for e in entries if e['name'] in names]
        for entry in entries:
            for field in ('map', 'sequence'):
                if not unreal.EditorAssetLibrary.does_asset_exist(entry[field]):
                    raise RuntimeError('Missing saved {}: {}. Use build=True.'.format(field, entry[field]))
        if render:
            return render_jobs(entries, resolution or (512 if preview else 1024),
                               samples or (8 if preview else 16))
        report('built', assets=[e['name'] for e in entries])
        return entries
    except Exception:
        report('failed', error=traceback.format_exc())
        unreal.log_error(traceback.format_exc())
        raise


if __name__ == '__main__':
    main()
